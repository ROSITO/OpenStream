import XCTest
@testable import OpenStream

final class MediaSegmentNormalizerTests: XCTestCase {
    func testStripsPNGDecoyBeforeMPEGTS() throws {
        // Minimal PNG 1x1 + TS sync bytes repeating.
        let png = Data([
            0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
            0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
            0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
            0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
            0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41,
            0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
            0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00,
            0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,
            0x42, 0x60, 0x82
        ])
        var ts = Data()
        for _ in 0..<3 {
            var packet = Data(repeating: 0xFF, count: 188)
            packet[0] = 0x47
            ts.append(packet)
        }
        let mixed = png + ts
        let result = MediaSegmentNormalizer.normalize(mixed)
        XCTAssertEqual(result.kind, .mpegts)
        XCTAssertGreaterThan(result.strippedBytes, 0)
        XCTAssertEqual(result.data[0], 0x47)
        XCTAssertEqual(MediaSegmentNormalizer.preferredExtension(for: .mpegts, currentExtension: "image"), "ts")
    }
}
